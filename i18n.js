(() => {
  const LANGS = ['en', 'uz', 'ru'];
  const STORE = 'ba-lang';
  const reduce = window.matchMedia('(prefers-reduced-motion: reduce)').matches;
  const dict = window.I18N;

  const pick = () => {
    try { const s = localStorage.getItem(STORE); if (LANGS.includes(s)) return s; } catch (e) {}
    const nav = (navigator.language || 'en').slice(0, 2).toLowerCase();
    return LANGS.includes(nav) ? nav : 'en';
  };

  const renderStory = (t) => {
    const el = document.getElementById('storyText');
    el.innerHTML = t.split(/\s+/).map((w) => {
      const key = w.includes('*');
      const clean = w.replace(/\*/g, '');
      return `<span class="w${key ? ' key' : ''}">${clean}</span>`;
    }).join(' ');
  };

  const renderMarquee = (words) => {
    const one = words.map((w) => `<span>${w}</span><i>✦</i>`).join('');
    document.getElementById('marquee').innerHTML = one + one;
  };

  const apply = (lang) => {
    const t = dict[lang];
    document.documentElement.lang = lang;
    document.querySelectorAll('[data-i18n]').forEach((el) => { const v = t[el.dataset.i18n]; if (v != null) el.textContent = v; });
    document.querySelectorAll('[data-i18n-html]').forEach((el) => { const v = t[el.dataset.i18nHtml]; if (v != null) el.innerHTML = v; });
    renderStory(t['story.text']);
    renderMarquee(t.marquee);
    const md = document.querySelector('meta[name="description"]');
    if (md) md.setAttribute('content', t['meta.desc']);
    document.querySelectorAll('.lang button').forEach((b) => b.setAttribute('aria-pressed', String(b.dataset.lang === lang)));
    movePill(lang, false);
    window.dispatchEvent(new CustomEvent('langchange', { detail: lang }));
  };

  // Sliding pill
  const group = document.querySelector('.lang');
  const pill = group.querySelector('.lang-pill');
  let current = null;
  function movePill(lang, animate) {
    const btn = group.querySelector(`[data-lang="${lang}"]`);
    if (!btn) return;
    pill.style.width = btn.offsetWidth + 'px';
    pill.style.transform = `translateX(${btn.offsetLeft}px)`;
    if (animate && !reduce) {
      pill.classList.remove('boing'); void pill.offsetWidth; pill.classList.add('boing');
      btn.classList.remove('pop'); void btn.offsetWidth; btn.classList.add('pop');
    }
  }

  const textNodes = () => [...document.querySelectorAll('[data-i18n],[data-i18n-html],#storyText,#marquee')]
    .filter((el) => { const r = el.getBoundingClientRect(); return r.bottom > -50 && r.top < innerHeight + 50; });

  const switchTo = (lang) => {
    if (lang === current) return;
    current = lang;
    try { localStorage.setItem(STORE, lang); } catch (e) {}
    movePill(lang, true);
    if (reduce || !Element.prototype.animate) { apply(lang); return; }
    const els = textNodes();
    const out = els.map((el) => el.animate(
      [{ opacity: 1, filter: 'blur(0)' }, { opacity: 0, filter: 'blur(8px)' }],
      { duration: 160, easing: 'ease-in', fill: 'forwards' }
    ));
    setTimeout(() => {
      apply(lang);
      out.forEach((a) => a.cancel());
      textNodes().forEach((el, i) => el.animate(
        [{ opacity: 0, filter: 'blur(8px)', transform: 'translateY(8px)' }, { opacity: 1, filter: 'blur(0)', transform: 'none' }],
        { duration: 520, delay: Math.min(i * 18, 260), easing: 'cubic-bezier(0.22, 1, 0.36, 1)', fill: 'backwards' }
      ));
    }, 170);
  };

  group.addEventListener('click', (e) => {
    const b = e.target.closest('button[data-lang]');
    if (b) switchTo(b.dataset.lang);
  });
  window.addEventListener('resize', () => movePill(current, false));
  document.fonts && document.fonts.ready.then(() => movePill(current, false));

  current = pick();
  apply(current);
})();
